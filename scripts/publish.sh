#!/usr/bin/env bash
#
# publish.sh — publish KOL-Dashboard to GitHub Pages and self-verify the deploy.
#
#   bash scripts/publish.sh
#
# Cycle:  gate (lint + build) -> diff -> commit -> push -> watch Actions -> verify live
#
# Safety: no force-push, no hard reset, no rebase/merge/tag/amend.
#         Only `git add -A`, `git commit -m`, `git push origin <current-branch>` are used.
#         On the deploy branch (main) it then watches the Actions run and verifies the
#         live site. On any other branch (e.g. an Agent Manager worktree) it pushes the
#         branch and stops — the deploy workflow only fires on push to main.

set -euo pipefail

# ── Configuration ───────────────────────────────────────────────────────────
REPO_SLUG="oneup24/KOL-Dashboard"
LIVE_BASE="https://oneup24.github.io/KOL-Dashboard"
NETLIFY_BASE="https://kol-24.netlify.app"   # the marketer's primary host
RUNS_API="https://api.github.com/repos/${REPO_SLUG}/actions/runs?per_page=5"
MARKER="dashboardUnlocked"          # only present in the new build
POLL_INTERVAL=15                  # seconds between Actions polls
POLL_ATTEMPTS=24                  # 24 x 15s = 6 minutes max watch window
VERIFY_ATTEMPTS=12                # 12 x 10s = 2 minutes max wait for Pages to propagate
ROUTES=(
  "/#/applications"
  "/#/campaigns/1"
  "/#/c/summer-collection-2026"
)

# ── State collected for the final summary ──────────────────────────────────
COMMIT_SHA=""
RUN_URL=""
RUN_STATUS=""
RUN_CONCLUSION=""
BUNDLE_PATH=""
BUNDLE_NAME=""
MARKER_COUNT=0
PUSHED=0
NETLIFY_STATE="not checked"
VERIFY_REACHABLE=0
VERIFY_BUNDLE_OK=0
VERIFY_BUNDLE_PATH=""
VERIFY_BUNDLE_NAME=""
VERIFY_MARKER_COUNT=0

# ── Helpers ────────────────────────────────────────────────────────────────
ROOT="$(cd "$(dirname "${BASH_SOURCE[0]}")/.." && pwd)"
info() { printf '%s\n' "$*"; }
step() { printf '\n== %s\n' "$*"; }

# warn <reason...> — loud but non-fatal. For findings the reader must not
# miss, but that must not block a release we cannot control from here.
warn() {
  printf '\n!! WARNING: %s\n' "$*" >&2
}

# fail <reason> [detail...] — print the detail, the FAIL summary, exit 1.
fail() {
  local reason="$1"; shift
  if [ "$#" -gt 0 ]; then
    printf '\n%s\n' "$*"
  fi
  printf '\n────────────────────────────────────────\n'
  printf ' PUBLISH RESULT: FAIL\n'
  printf ' failed:  %s\n' "${reason}"
  printf ' commit:  %s\n' "${COMMIT_SHA:-<none>}"
  printf ' deploy:  %s\n' "${RUN_URL:-<none>}"
  printf ' live:    %s/\n' "${LIVE_BASE}/"
  printf ' netlify: %s/  (%s)\n' "${NETLIFY_BASE}" "${NETLIFY_STATE}"
  printf '────────────────────────────────────────\n'
  exit 1
}


# ── Commit message ──────────────────────────────────────────────────────────
# Derive a clear message from the ACTUAL staged diff. Never reuse a hardcoded
# one — it would describe a different change.
auto_commit_message() {
  local files count areas subject stats
  files="$(git diff --cached --name-only)"
  count="$(printf '%s\n' "$files" | grep -c . || true)"
  areas="$(printf '%s\n' "$files" | awk -F/ 'NF>0{print $1}' | sort -u | paste -sd', ' -)"

  if [ "$count" -eq 1 ]; then
    subject="Update $(printf '%s\n' "$files" | head -n1)"
  elif [ "$count" -gt 1 ]; then
    subject="Update ${count} files (${areas})"
  else
    subject="Update"
  fi

  # last line of --stat is the "N files changed" summary; the rest is per-file
  stats="$(git diff --cached --stat | sed '$d')"

  local summary
  summary="$(git diff --cached --shortstat | sed 's/^ *//')"

  printf '%s\n\n%s\n\n%s\n\nGenerated by scripts/publish.sh on %s.\n' \
    "$subject" "$stats" "$summary" "$(date '+%Y-%m-%d %H:%M')"
}

# Catch anything unexpected and still emit a summary.
on_error() {
  local code="$1"
  trap - ERR
  fail "UNEXPECTED ERROR — exit code ${code}"
}
trap 'on_error $?' ERR

# Resolve the repo root from the script location so it can be run from anywhere.
SCRIPT_DIR="$(cd "$(dirname "${BASH_SOURCE[0]}")" && pwd)"
REPO_ROOT="$(cd "${SCRIPT_DIR}/.." && pwd)"
cd "${REPO_ROOT}"

# ── 1. Header ──────────────────────────────────────────────────────────────
if ! git rev-parse --is-inside-work-tree >/dev/null 2>&1; then
  fail "PRE-FLIGHT FAILED — not a git work tree: ${REPO_ROOT}"
fi

BRANCH="$(git rev-parse --abbrev-ref HEAD)"
HEAD_SHA="$(git rev-parse HEAD)"

info "========================================"
info " KOL-Dashboard publish"
info "========================================"
info "repo:    ${REPO_ROOT}"
info "branch:  ${BRANCH}"
info "HEAD:    ${HEAD_SHA}"

DEPLOY_BRANCH="main"
if [ "${BRANCH}" != "${DEPLOY_BRANCH}" ]; then
  info "branch '${BRANCH}' is not '${DEPLOY_BRANCH}' — this run will push the branch and stop."
  info "It will NOT deploy: the workflow only fires on push to ${DEPLOY_BRANCH}."
  info "Open a pull request to merge it instead."
else
  info "branch '${BRANCH}' — this push triggers the deploy workflow."
fi

# ── 2. Gate: lint + build ─────────────────────────────────────────────────
step "GATE — npm run lint"
if ! lint_out="$(npm run lint 2>&1)"; then
  printf '%s\n' "${lint_out}"
  fail "GATE FAILED — npm run lint"
fi
printf '%s\n' "${lint_out}" | tail -n 20

step "GATE — npm run build"
if ! build_out="$(npm run build 2>&1)"; then
  printf '%s\n' "${build_out}"
  fail "GATE FAILED — npm run build"
fi
printf '%s\n' "${build_out}" | tail -n 30
if grep -q "larger than 500 kB" <<< "${build_out}"; then
  info "note: the chunk-size warning above is expected and is not a failure."
fi
info "gate: lint OK, build OK"

# ── 3. Diff stat: exactly what is about to be published ───────────────────
step "DIFF STAT — what will be published"
git diff --stat
git status --short

# ── 4. Commit ──────────────────────────────────────────────────────────────
step "COMMIT"
if ! git add -A; then
  fail "COMMIT FAILED — git add -A"
fi

if git diff --cached --quiet; then
  info "Nothing to commit, tree already clean — skipping commit and push."
  COMMIT_SHA="$(git rev-parse HEAD)"
else
  git diff --cached --stat

  # The commit message may be supplied by the release agent in .release-message
  # (it writes it there so the founder can read it before approving). If that
  # file is absent, derive a message from the real staged diff — never reuse a
  # hardcoded one, it would describe a different change.
  if [ -f "${ROOT}/.release-message" ]; then
    COMMIT_MESSAGE="$(cat "${ROOT}/.release-message")"
    info "using commit message from .release-message"
  else
    COMMIT_MESSAGE="$(auto_commit_message)"
    info "no .release-message found — generated the message from the diff"
  fi

  if [ -z "${COMMIT_MESSAGE//[[:space:]]/}" ]; then
    fail "COMMIT MESSAGE IS EMPTY — refusing to commit with a blank message"
  fi

  if ! git commit -m "${COMMIT_MESSAGE}"; then
    fail "COMMIT FAILED — git commit -m"
  fi
  COMMIT_SHA="$(git rev-parse HEAD)"
  PUSHED=1
  info "created commit ${COMMIT_SHA}"
fi

# ── 5. Push ────────────────────────────────────────────────────────────────
# Push the CURRENT branch, never a hardcoded one — inside an Agent Manager
# worktree the current branch is the worktree's own feature branch, and
# "git push origin main" would publish the wrong tree.
step "PUSH — git push origin ${BRANCH}"
if [ "${PUSHED}" -eq 1 ]; then
  if ! push_out="$(git push origin "${BRANCH}" 2>&1)"; then
    printf '%s\n' "${push_out}"
    fail "PUSH FAILED — git push origin ${BRANCH}"
  fi
  printf '%s\n' "${push_out}"
else
  info "skipped — nothing to commit"
fi

# ── 5b. Not the deploy branch — stop here, before the deploy watch ─────────
if [ "${BRANCH}" != "${DEPLOY_BRANCH}" ]; then
  printf '\n────────────────────────────────────────\n'
  printf ' PUSH RESULT: PASS (branch pushed, no deploy)\n'
  printf ' branch:  %s\n' "${BRANCH}"
  printf ' commit:  %s\n' "${COMMIT_SHA}"
  printf ' next:    open a pull request %s → %s\n' "${BRANCH}" "${DEPLOY_BRANCH}"
  printf '           %s\n' "https://github.com/oneup24/KOL-Dashboard/compare/${DEPLOY_BRANCH}...${BRANCH}"
  printf '────────────────────────────────────────\n'
  exit 0
fi

# ── 6. Watch the deploy workflow ──────────────────────────────────────────
# Reads the Actions API on stdin, prints "<status>|<conclusion>|<url>" for the
# run whose head_sha matches $1. Exit 0 = found, 2 = unparseable, 3 = not yet.
parse_run() {
  python3 -c '
import sys, json, re

try:
    raw = re.sub(r"[\x00-\x1f]+", " ", sys.stdin.read())
    data = json.loads(raw)
except Exception as exc:
    sys.stderr.write("api parse error: %s\n" % exc)
    sys.exit(2)

target = sys.argv[1]
runs = data.get("workflow_runs")
if runs is None:
    sys.stderr.write("unexpected api payload (no workflow_runs)\n")
    sys.exit(2)
for run in runs:
    if run.get("head_sha") == target:
        sys.stdout.write("%s|%s|%s\n" % (
            run.get("status") or "",
            run.get("conclusion") or "",
            run.get("html_url") or "",
        ))
        sys.exit(0)
sys.exit(3)
' "$1"
}

if [ "${PUSHED}" -eq 1 ]; then
  step "WATCH DEPLOY — Actions run for ${COMMIT_SHA}"
  last_status=""
  last_conclusion=""
  attempt=0
  while [ "${attempt}" -lt "${POLL_ATTEMPTS}" ]; do
    attempt=$((attempt + 1))
    api_body="$(curl -s --max-time 30 -H "Accept: application/vnd.github+json" "${RUNS_API}" || true)"
    if parsed="$(printf '%s' "${api_body}" | parse_run "${COMMIT_SHA}")"; then
      parse_rc=0
    else
      parse_rc=$?
    fi

    case "${parse_rc}" in
      0)
        IFS='|' read -r st concl url <<< "${parsed}" || true
        RUN_STATUS="${st}"
        RUN_CONCLUSION="${concl}"
        RUN_URL="${url}"
        if [ "${st}" != "${last_status}" ] || [ "${concl}" != "${last_conclusion}" ]; then
          info "  [$(date '+%H:%M:%S')] ${st}${concl:+ / ${concl}}  ${url}"
          last_status="${st}"
          last_conclusion="${concl}"
        fi
        if [ "${st}" = "completed" ]; then
          break
        fi
        ;;
      3)
        info "  [$(date '+%H:%M:%S')] waiting for the run to appear (attempt ${attempt}/${POLL_ATTEMPTS})"
        ;;
      *)
        info "  [$(date '+%H:%M:%S')] could not read the Actions API (attempt ${attempt}/${POLL_ATTEMPTS})"
        ;;
    esac

    if [ "${attempt}" -lt "${POLL_ATTEMPTS}" ]; then
      sleep "${POLL_INTERVAL}"
    fi
  done

  if [ "${RUN_STATUS}" != "completed" ]; then
    fail "DEPLOY FAILED — workflow did not complete within $((POLL_ATTEMPTS * POLL_INTERVAL))s" \
         "Last known run: ${RUN_URL:-<none>}"
  fi
  if [ "${RUN_CONCLUSION}" != "success" ]; then
    fail "DEPLOY FAILED — workflow conclusion: ${RUN_CONCLUSION:-unknown}" \
         "Failing run: ${RUN_URL}"
  fi
  info "deploy succeeded: ${RUN_URL}"
else
  info "watch: skipped — no new commit to deploy"
fi

# ── 7. Verify live ────────────────────────────────────────────────────────
step "VERIFY LIVE — ${LIVE_BASE}/"

http_code() {
  local code
  code="$(curl -s --max-time 30 -o /dev/null -w "%{http_code}\n" "$1" 2>/dev/null | tr -d '[:space:]' || true)"
  printf '%s' "${code:-000}"
}

index_code="$(http_code "${LIVE_BASE}/")"
if [ "${index_code}" != "200" ]; then
  fail "VERIFY FAILED — ${LIVE_BASE}/ returned HTTP ${index_code}"
fi
info "  index: HTTP 200"

for route in "${ROUTES[@]}"; do
  code="$(http_code "${LIVE_BASE}${route}")"
  if [ "${code}" != "200" ]; then
    fail "VERIFY FAILED — route ${route} returned HTTP ${code}"
  fi
  info "  route ${route}: HTTP 200"
done

# Pull the live bundle filename out of the live index.html, fetch that exact
# bundle and count the marker. The old live bundle has 0 matches for the
# marker — "${MARKER}" only exists in the new build, so a stale bundle can
# never satisfy the check.
#
# bundle_path_of <index_html>       → the "assets/index-<hash>.js" the index references
# marker_count <base> <bundle_path> → how often "${MARKER}" occurs in that bundle
# verify_marker <base> <label>      → retries both until the marker shows up
#
# GitHub Pages and Netlify serve the very same bundle from "<base>/assets/…";
# only the root differs, so both hosts go through the same helpers.
bundle_path_of() {
  local index_html="$1"
  printf '%s' "${index_html}" | grep -oE 'assets/index-[A-Za-z0-9_-]+\.js' | head -n 1
}

marker_count() {
  local base="$1" bundle_path="$2" body count
  body="$(curl -s --max-time 60 "${base}/${bundle_path}")" || return 1
  count="$(printf '%s' "${body}" | python3 -c 'import sys; print(sys.stdin.read().count("dashboardUnlocked"))' 2>/dev/null || printf '0')"
  printf '%s' "${count}"
}

# verify_marker <base> <label> — fetch the index, confirm it is the app shell,
# locate the bundle it references and count the marker in it. Retries until
# the marker shows up or the retry window closes.
#
# Sets VERIFY_REACHABLE   (the host answered with the app shell)
#       VERIFY_BUNDLE_OK  (the bundle itself could be read)
#       VERIFY_BUNDLE_PATH / VERIFY_BUNDLE_NAME / VERIFY_MARKER_COUNT
# Returns 0 as soon as the marker is found, 1 when the window closed.
verify_marker() {
  local base="$1" label="$2"
  local attempt=0 index_html bundle_path count
  VERIFY_REACHABLE=0
  VERIFY_BUNDLE_OK=0
  VERIFY_BUNDLE_PATH=""
  VERIFY_BUNDLE_NAME=""
  VERIFY_MARKER_COUNT=0

  while [ "${attempt}" -lt "${VERIFY_ATTEMPTS}" ]; do
    attempt=$((attempt + 1))
    index_html="$(curl -s --max-time 30 "${base}/")" || index_html=""

    # The app shell must be there — a 404 or an error page is not the SPA.
    if [ -n "${index_html}" ]; then
      case "${index_html}" in
        *'<div id="root">'*) ;;
        *) index_html="" ;;
      esac
    fi

    bundle_path=""
    if [ -n "${index_html}" ]; then
      bundle_path="$(bundle_path_of "${index_html}")" || bundle_path=""
    fi

    if [ -n "${bundle_path}" ]; then
      VERIFY_REACHABLE=1
      VERIFY_BUNDLE_PATH="${bundle_path}"
      VERIFY_BUNDLE_NAME="${bundle_path##*/}"
      count="$(marker_count "${base}" "${bundle_path}")" || count=""
      if [ -n "${count}" ]; then
        VERIFY_BUNDLE_OK=1
        VERIFY_MARKER_COUNT="${count}"
        if [ "${VERIFY_MARKER_COUNT}" -gt 0 ]; then
          return 0
        fi
      fi
    fi

    if [ "${attempt}" -lt "${VERIFY_ATTEMPTS}" ]; then
      info "  ${label}: marker '${MARKER}' not visible yet (attempt ${attempt}/${VERIFY_ATTEMPTS}) — waiting for the CDN to propagate"
      sleep 10
    fi
  done

  return 1
}

# GitHub Pages — the deploy this script just pushed and watched.
if ! verify_marker "${LIVE_BASE}" "pages"; then
  fail "VERIFY FAILED — marker '${MARKER}' not found in the live bundle" \
       "Live bundle: ${VERIFY_BUNDLE_NAME:-<no bundle found>}"
fi
BUNDLE_PATH="${VERIFY_BUNDLE_PATH}"
BUNDLE_NAME="${VERIFY_BUNDLE_NAME}"
MARKER_COUNT="${VERIFY_MARKER_COUNT}"
info "  bundle ${BUNDLE_NAME} contains '${MARKER}' × ${MARKER_COUNT}"

# Netlify — the marketer's primary host. It builds from the same push, but on
# its own pipeline, so it can lag behind GitHub Pages.
step "VERIFY NETLIFY — ${NETLIFY_BASE}/"
if verify_marker "${NETLIFY_BASE}" "netlify"; then
  NETLIFY_STATE="current"
  info "  bundle ${VERIFY_BUNDLE_NAME} contains '${MARKER}' × ${VERIFY_MARKER_COUNT}"
elif [ "${VERIFY_REACHABLE}" -eq 1 ] && [ "${VERIFY_BUNDLE_OK}" -eq 1 ]; then
  # Netlify answered and served a bundle — it is simply the old one. That is
  # the same condition the GitHub Pages check fails on, so it fails here too.
  NETLIFY_STATE="old bundle"
  fail "VERIFY FAILED — Netlify is still serving the old bundle" \
       "Netlify bundle: ${VERIFY_BUNDLE_NAME}" \
       "marker '${MARKER}' not found after $((VERIFY_ATTEMPTS * 10))s"
else
  # Netlify was unreachable or still propagating. Never block the release on a
  # host this script does not control — warn loudly and let it be checked.
  NETLIFY_STATE="unavailable"
  warn "Netlify did not serve the new bundle within $((VERIFY_ATTEMPTS * 10))s — the release continues, but check ${NETLIFY_BASE}/ manually."
fi

# ── 8. Summary ─────────────────────────────────────────────────────────────
printf '\n────────────────────────────────────────\n'
printf ' PUBLISH RESULT: PASS\n'
printf ' commit:  %s\n' "${COMMIT_SHA}"
printf ' deploy:  %s\n' "${RUN_URL:-<skipped: nothing to commit>}"
printf ' live:    %s/\n' "${LIVE_BASE}/"
printf ' bundle:  %s  (%s × %s)\n' "${BUNDLE_NAME}" "${MARKER}" "${MARKER_COUNT}"
printf ' netlify: %s/  (%s)\n' "${NETLIFY_BASE}" "${NETLIFY_STATE}"
printf '────────────────────────────────────────\n'

exit 0
