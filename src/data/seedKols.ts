/**
 * Normalises a social handle for CRM lookups:
 * trims, lowercases, drops a leading "@" and removes inner whitespace.
 *
 * @example normaliseHandle(" @Elena_Styles ") // "elena_styles"
 */
export const normaliseHandle = (handle: string): string =>
  handle.trim().toLowerCase().replace(/^@/, "").replace(/\s+/g, "");

/**
 * Parses a follower count that may arrive from a free-text public form
 * ("120K", "1.2M", "850") into a plain number.
 */
export const parseFollowerCount = (raw: string | number): number => {
  if (typeof raw === "number") return Number.isFinite(raw) ? Math.round(raw) : 0;
  const cleaned = raw.trim().toLowerCase().replace(/,/g, "");
  if (!cleaned) return 0;
  const match = /^(\d+(?:\.\d+)?)\s*([km])?/.exec(cleaned);
  if (!match) return 0;
  const value = parseFloat(match[1]);
  if (!Number.isFinite(value)) return 0;
  const multiplier = match[2] === "k" ? 1_000 : match[2] === "m" ? 1_000_000 : 1;
  return Math.round(value * multiplier);
};

/**
 * Formats a numeric follower count for display: 120000 -> "120K".
 */
export const formatFollowers = (followers: number): string => {
  if (!Number.isFinite(followers) || followers <= 0) return "0";
  if (followers >= 1_000_000) {
    const millions = followers / 1_000_000;
    return `${millions % 1 === 0 ? millions.toFixed(0) : millions.toFixed(1)}M`;
  }
  if (followers >= 1_000) {
    const thousands = followers / 1_000;
    return `${thousands % 1 === 0 ? thousands.toFixed(0) : thousands.toFixed(1)}K`;
  }
  return String(Math.round(followers));
};

